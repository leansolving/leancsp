def write_csv_files(detailed: List[SolverResult], aggregated: List[AggregatedResult]):
    """Write results to CSV files."""

    # Detailed results
    with open(RESULTS_DIR / "detailed_results.csv", 'w', newline='') as f:
        fieldnames = ['circuit_type', 'size', 'variant', 'solver', 'backend',
                     'status', 'run_id', 'wall_time', 'solve_time']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in detailed:
            writer.writerow(r.to_dict())

    print(f"✓ Detailed: {RESULTS_DIR / 'detailed_results.csv'}")

    # Aggregated results
    with open(RESULTS_DIR / "aggregated_results.csv", 'w', newline='') as f:
        fieldnames = ['circuit_type', 'size', 'variant', 'solver', 'backend',
                     'status', 'time_median', 'time_mean', 'time_std',
                     'time_min', 'time_max', 'num_runs']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in aggregated:
            writer.writerow(r.to_dict())

    print(f"✓ Aggregated: {RESULTS_DIR / 'aggregated_results.csv'}")

def write_summary(aggregated: List[AggregatedResult]):
    """Write human-readable summary."""

    with open(RESULTS_DIR / "summary.txt", 'w') as f:
        f.write("Parity Path Theorem - Experimental Results\n")
        f.write("=" * 80 + "\n\n")

        circuit_types = sorted(set(r.circuit_type for r in aggregated))

        for ctype in circuit_types:
            f.write(f"\n{ctype.upper()}\n")
            f.write("-" * 80 + "\n")

            type_results = [r for r in aggregated if r.circuit_type == ctype]
            solvers = sorted(set(r.solver for r in type_results))
            sizes = sorted(set(r.size for r in type_results))

            for solver in solvers:
                f.write(f"\n{solver}:\n")
                f.write(f"{'Size':<8} {'BASE':<12} {'SBC(1)':<12} {'SBC(half)':<12} {'Speedup(1)':<12} {'Speedup(half)':<12}\n")
                f.write("-" * 80 + "\n")

                for size in sizes:
                    base = next((r for r in type_results
                                if r.size == size and r.variant == 'base' and r.solver == solver), None)
                    sbc = next((r for r in type_results
                               if r.size == size and r.variant == 'sbc' and r.solver == solver), None)
                    sbc_half = next((r for r in type_results
                               if r.size == size and r.variant == 'sbc_half' and r.solver == solver), None)

                    if base:
                        base_time = base.time_median
                        sbc_time = sbc.time_median if sbc else None
                        sbc_half_time = sbc_half.time_median if sbc_half else None

                        base_str = f"{base_time:.4f}s" if base_time else "TIMEOUT"
                        sbc_str = f"{sbc_time:.4f}s" if sbc_time else "TIMEOUT"
                        sbc_half_str = f"{sbc_half_time:.4f}s" if sbc_half_time else "TIMEOUT"

                        if base_time and sbc_time and sbc_time > 0:
                            speedup1 = base_time / sbc_time
                            speedup1_str = f"{speedup1:.2f}x"
                        else:
                            speedup1_str = "-"

                        if base_time and sbc_half_time and sbc_half_time > 0:
                            speedup_half = base_time / sbc_half_time
                            speedup_half_str = f"{speedup_half:.2f}x"
                        else:
                            speedup_half_str = "-"

                        f.write(f"{size:<8} {base_str:<12} {sbc_str:<12} {sbc_half_str:<12} "
                               f"{speedup1_str:<12} {speedup_half_str:<12}\n")

    print(f"✓ Summary: {RESULTS_DIR / 'summary.txt'}")

def generate_plots(aggregated: List[AggregatedResult]):
    """Generate visualization plots."""

    try:
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        print("matplotlib not available - skipping plots")
        return

    SOLVER_COLORS = {
        'gecode': '#1f77b4',
        'chuffed': '#ff7f0e',
        'z3': '#2ca02c',
        'cvc5': '#d62728'
    }

    VARIANT_STYLES = {
        'base': '-',
        'sbc': '--',
        'sbc_half': ':'
    }

    VARIANT_MARKERS = {
        'base': 'o',
        'sbc': 's',
        'sbc_half': '^'
    }

    circuit_types = sorted(set(r.circuit_type for r in aggregated))

    # ========== Per Circuit Type Scaling Plots ==========
    for ctype in circuit_types:
        type_results = [r for r in aggregated if r.circuit_type == ctype]
        solvers = sorted(set(r.solver for r in type_results))
        sizes = sorted(set(r.size for r in type_results))

        fig, ax = plt.subplots(figsize=(10, 6))

        for solver in solvers:
            for variant in ['base', 'sbc', 'sbc_half']:
                times = []
                valid_sizes = []

                for size in sizes:
                    result = next((r for r in type_results
                                  if r.size == size and r.variant == variant and r.solver == solver), None)
                    if result and result.time_median:
                        times.append(result.time_median)
                        valid_sizes.append(size)

                if valid_sizes:
                    ax.plot(valid_sizes, times,
                           color=SOLVER_COLORS.get(solver, 'gray'),
                           linestyle=VARIANT_STYLES[variant],
                           marker=VARIANT_MARKERS[variant],
                           linewidth=2, markersize=6,
                           label=f"{solver} ({variant})")

        ax.set_xlabel("Circuit Size (inputs)", fontsize=12)
        ax.set_ylabel("Median Time (seconds)", fontsize=12)
        ax.set_title(f"Scaling: {ctype}", fontsize=14)
        ax.legend(loc='upper left', fontsize=9)
        ax.grid(True, alpha=0.3)
        ax.set_xlim(left=min(sizes) - 1 if sizes else 0)
        ax.set_ylim(bottom=0)

        plt.tight_layout()
        plt.savefig(PLOTS_DIR / f"scaling_{ctype}.png", dpi=150, bbox_inches='tight')
        plt.savefig(PLOTS_DIR / f"scaling_{ctype}.pdf", bbox_inches='tight')
        plt.close()

    print(f"✓ Scaling plots: {PLOTS_DIR}")

    # ========== Speedup Bar Chart (sbc - 1 input fixed) ==========
    fig, ax = plt.subplots(figsize=(12, 6))

    solvers = sorted(set(r.solver for r in aggregated))
    x = np.arange(len(circuit_types))
    width = 0.2

    for i, solver in enumerate(solvers):
        speedups = []
        for ctype in circuit_types:
            type_results = [r for r in aggregated if r.circuit_type == ctype and r.solver == solver]

            base_times = [r.time_median for r in type_results if r.variant == 'base' and r.time_median]
            sbc_times = [r.time_median for r in type_results if r.variant == 'sbc' and r.time_median]

            if base_times and sbc_times:
                avg_base = np.mean(base_times)
                avg_sbc = np.mean(sbc_times)
                if avg_sbc > 0:
                    speedups.append(avg_base / avg_sbc)
                else:
                    speedups.append(1.0)
            else:
                speedups.append(1.0)

        bars = ax.bar(x + i * width, speedups, width,
                     label=solver, color=SOLVER_COLORS.get(solver, 'gray'), alpha=0.8)

    ax.axhline(y=1, color='black', linestyle='--', linewidth=1, alpha=0.5)
    ax.set_xlabel("Circuit Type", fontsize=12)
    ax.set_ylabel("Speedup (base / sbc)", fontsize=12)
    ax.set_title("Speedup from Parity-Based Input Fixing (1 input)", fontsize=14)
    ax.set_xticks(x + width * (len(solvers) - 1) / 2)
    ax.set_xticklabels(circuit_types, rotation=45, ha='right')
    ax.legend()
    ax.grid(True, alpha=0.3, axis='y')

    plt.tight_layout()
    plt.savefig(PLOTS_DIR / "speedup_by_type_sbc.png", dpi=150, bbox_inches='tight')
    plt.savefig(PLOTS_DIR / "speedup_by_type_sbc.pdf", bbox_inches='tight')
    plt.close()

    print(f"✓ Speedup plot (sbc): {PLOTS_DIR / 'speedup_by_type_sbc.png'}")

    # ========== Speedup Bar Chart (sbc_half - half inputs fixed) ==========
    fig, ax = plt.subplots(figsize=(12, 6))

    for i, solver in enumerate(solvers):
        speedups = []
        for ctype in circuit_types:
            type_results = [r for r in aggregated if r.circuit_type == ctype and r.solver == solver]

            base_times = [r.time_median for r in type_results if r.variant == 'base' and r.time_median]
            sbc_half_times = [r.time_median for r in type_results if r.variant == 'sbc_half' and r.time_median]

            if base_times and sbc_half_times:
                avg_base = np.mean(base_times)
                avg_sbc_half = np.mean(sbc_half_times)
                if avg_sbc_half > 0:
                    speedups.append(avg_base / avg_sbc_half)
                else:
                    speedups.append(1.0)
            else:
                speedups.append(1.0)

        bars = ax.bar(x + i * width, speedups, width,
                     label=solver, color=SOLVER_COLORS.get(solver, 'gray'), alpha=0.8)

    ax.axhline(y=1, color='black', linestyle='--', linewidth=1, alpha=0.5)
    ax.set_xlabel("Circuit Type", fontsize=12)
    ax.set_ylabel("Speedup (base / sbc_half)", fontsize=12)
    ax.set_title("Speedup from Parity-Based Input Fixing (half inputs)", fontsize=14)
    ax.set_xticks(x + width * (len(solvers) - 1) / 2)
    ax.set_xticklabels(circuit_types, rotation=45, ha='right')
