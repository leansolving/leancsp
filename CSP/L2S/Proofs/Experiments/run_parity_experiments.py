def discover_instances() -> List[Tuple[str, int, str, Path, Optional[Path]]]:
    """Discover test instances for parity circuit types."""
    instances = []

    for circuit_dir in MZN_DIR.iterdir():
        if not circuit_dir.is_dir():
            continue

        circuit_type = circuit_dir.name

        # Only process parity circuit types
        if circuit_type not in PARITY_CIRCUIT_TYPES:
            continue

        for mzn_file in sorted(circuit_dir.glob("*.mzn")):
            stem = mzn_file.stem

            if stem.startswith("base_"):
                variant = "base"
                size_str = stem[5:]
            elif stem.startswith("sbc_half_"):
                variant = "sbc_half"
                size_str = stem[9:]
            elif stem.startswith("sbc_"):
                variant = "sbc"
                size_str = stem[4:]
            else:
                continue

            try:
                size = int(size_str)
            except ValueError:
                continue

            # Check for corresponding SMT file
            smt_file = SMT_DIR / circuit_type / f"{stem}.smt2"
            smt_path = smt_file if smt_file.exists() else None

            instances.append((circuit_type, size, variant, mzn_file, smt_path))

    instances.sort(key=lambda x: (x[0], x[1], x[2]))
    return instances

