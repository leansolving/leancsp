def run_minizinc(mzn_file: Path, solver: str) -> SolverResult:
    """Run MiniZinc solver on a file."""
    result = SolverResult(
        circuit_type='', size=0, variant='', solver=solver, backend='minizinc',
        status='UNKNOWN'
    )

    try:
        start = time.time()
        proc = subprocess.run(
            ['minizinc', '--solver', solver, '--statistics',
             '--solver-statistics', '--json-stream', str(mzn_file)],
            capture_output=True,
            text=True,
            timeout=TIMEOUT
        )
        result.wall_time = time.time() - start

        # Parse status from JSON output
        result.status = 'UNKNOWN'
        for line in proc.stdout.splitlines():
            if line.startswith('{'):
                try:
                    obj = json.loads(line)
                    if obj.get('type') == 'solution':
                        result.status = 'SAT'
                    elif obj.get('type') == 'status':
                        status_val = obj.get('status', '').upper()
                        if 'SATISFIED' in status_val or 'OPTIMAL' in status_val:
                            result.status = 'SAT'
                        elif 'UNSATISFIABLE' in status_val:
                            result.status = 'UNSAT'
                    elif obj.get('type') == 'statistics':
                        stats = obj.get('statistics', {})
                        if 'solveTime' in stats:
                            result.solve_time = stats['solveTime']
                except json.JSONDecodeError:
                    pass

    except subprocess.TimeoutExpired:
        result.status = 'TIMEOUT'
        result.wall_time = TIMEOUT
    except FileNotFoundError:
        result.status = 'NOT_FOUND'

    return result

def run_smt(smt_file: Path, solver: str) -> SolverResult:
    """Run SMT solver on a file."""
    result = SolverResult(
        circuit_type='', size=0, variant='', solver=solver, backend='smt',
        status='UNKNOWN'
    )

    try:
        start = time.time()

        if solver == 'z3':
            cmd = ['z3', '-st', str(smt_file)]
        elif solver == 'cvc5':
            cmd = ['cvc5', '--stats', str(smt_file)]
        else:
            return result

        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=TIMEOUT)
        result.wall_time = time.time() - start

        output = (proc.stdout + proc.stderr).lower()
        if 'unsat' in output:
            result.status = 'UNSAT'
        elif 'sat' in output:
            result.status = 'SAT'

    except subprocess.TimeoutExpired:
        result.status = 'TIMEOUT'
        result.wall_time = TIMEOUT
    except FileNotFoundError:
        result.status = 'NOT_FOUND'

    return result

