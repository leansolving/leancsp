def aggregate_results(results: List[SolverResult]) -> AggregatedResult:
    """Aggregate multiple runs into summary statistics."""
    if not results:
        return AggregatedResult(
            circuit_type='', size=0, variant='', solver='', backend='',
            status='UNKNOWN'
        )

    times = [r.wall_time for r in results if r.wall_time and r.status not in ('TIMEOUT', 'ERROR')]

    return AggregatedResult(
        circuit_type=results[0].circuit_type,
        size=results[0].size,
        variant=results[0].variant,
        solver=results[0].solver,
        backend=results[0].backend,
        status=max(set(r.status for r in results), key=lambda s: [r.status for r in results].count(s)),
        time_median=statistics.median(times) if times else None,
        time_mean=statistics.mean(times) if times else None,
        time_std=statistics.stdev(times) if len(times) > 1 else 0.0 if times else None,
        time_min=min(times) if times else None,
        time_max=max(times) if times else None,
        num_runs=len(results)
    )

