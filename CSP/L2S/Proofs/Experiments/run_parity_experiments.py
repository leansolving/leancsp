def run_experiments() -> Tuple[List[SolverResult], List[AggregatedResult]]:
    """Run all parity circuit experiments."""

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)

    instances = discover_instances()
    print(f"Discovered {len(instances)} instances")

    mzn_solvers = ['gecode', 'chuffed']
    smt_solvers = ['z3', 'cvc5']

    all_results = []
    aggregated_results = []

    total = len(instances) * (len(mzn_solvers) + len(smt_solvers)) * (NUM_RUNS + 1)  # +1 for warmup
    current = 0

    print(f"\nRunning experiments (timeout={TIMEOUT}s, runs={NUM_RUNS})...")
    print(f"Total solver calls: {total}\n")

    for circuit_type, size, variant, mzn_file, smt_file in instances:

        # MiniZinc solvers
        for solver in mzn_solvers:
            instance_name = f"{circuit_type} n={size} {variant}"
            run_results = []

            for run_id in range(NUM_RUNS + 1):  # +1 for warmup
                current += 1
                is_warmup = run_id == 0

                label = "warmup" if is_warmup else f"run {run_id}"
                print(f"[{current}/{total}] {instance_name:40s} {solver:8s} ({label}) ... ", end='', flush=True)

                result = run_minizinc(mzn_file, solver)
                result.circuit_type = circuit_type
                result.size = size
                result.variant = variant
                result.run_id = run_id

                time_str = f"{result.wall_time:.3f}s" if result.wall_time else "N/A"
                print(f"{time_str} ({result.status})")

                if not is_warmup:
                    run_results.append(result)
                    all_results.append(result)

            if run_results:
                agg = aggregate_results(run_results)
                aggregated_results.append(agg)

        # SMT solvers
        if smt_file:
            for solver in smt_solvers:
                instance_name = f"{circuit_type} n={size} {variant}"
                run_results = []

                for run_id in range(NUM_RUNS + 1):
                    current += 1
                    is_warmup = run_id == 0

                    label = "warmup" if is_warmup else f"run {run_id}"
                    print(f"[{current}/{total}] {instance_name:40s} {solver:8s} ({label}) ... ", end='', flush=True)

                    result = run_smt(smt_file, solver)
                    result.circuit_type = circuit_type
                    result.size = size
                    result.variant = variant
                    result.run_id = run_id

                    time_str = f"{result.wall_time:.3f}s" if result.wall_time else "N/A"
                    print(f"{time_str} ({result.status})")

                    if not is_warmup:
                        run_results.append(result)
                        all_results.append(result)

                if run_results:
                    agg = aggregate_results(run_results)
                    aggregated_results.append(agg)

    return all_results, aggregated_results

