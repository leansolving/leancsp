#!/usr/bin/env python3
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pbgen

REPO = Path(__file__).resolve().parent.parent.parent
CERT_DIR = REPO / "CSP" / "L2S" / "Backends" / "PB" / "Problems" / "certs"
ROUNDINGSAT = os.environ.get("ROUNDINGSAT",
                             "/home/pablo/projects/roundingsat/build/roundingsat")


def gen_cert(k: int) -> str:
    """RoundingSat + veripb on pbgen's OPB -> Problems/certs/mutilated<2k>.pbp."""
    board = 2 * k
    opb = Path(f"/tmp/mutilated{board}.opb")
    log = Path(f"/tmp/mutilated{board}.pbp")
    cert = CERT_DIR / f"mutilated{board}.pbp"
    opb.write_text(pbgen.mutilated_opb(k))

    out = subprocess.run([ROUNDINGSAT, str(opb), f"--proof-log={log}"],
                         capture_output=True, text=True).stdout
    if "s UNSATISFIABLE" not in out:
        sys.exit(f"ERROR: roundingsat did not report UNSATISFIABLE for k={k}")
    out = subprocess.run(["veripb", "--elaborate", str(cert), str(opb), str(log)],
                         capture_output=True, text=True)
    if "VERIFIED" not in out.stdout + out.stderr:
        sys.exit(f"ERROR: veripb failed to verify k={k}")
    print(f"wrote {cert}", file=sys.stderr)
    return cert.read_text()


def gen(k: int, cert: str) -> str:
    nplace, covers = pbgen._mutilated_geometry(k)
    board = 2 * k
    ns = f"MutilatedChessboard{board}"
    V = f"_root_.Vector (VarType {nplace})"

    # --- the CSP: per-present-cell exactly-one over its covering placements ---
    cell_lines = []
    for (r, c), cov in covers:
        arr = ", ".join(str(p) for p in cov)
        cell_lines.append(
            f"    -- cell ({r}, {c})\n"
            f"    sum_eq (⟨#[{arr}], rfl⟩ : {V} {len(cov)}) 1")
    csp_body = ",\n".join(cell_lines)

    return f'''import CSP.L2S.Backends.PB.GenericEncode
import CSP.L2S.Constraints

namespace CSP.L2S.PB.{ns}

open CSP.L2S CSP.L2S.PB

/-!
# PB backend — end-to-end verified UNSAT for the {board} × {board} mutilated chessboard

A scaling checkpoint (see `experiments/README.md`) generalising the 4 × 4 instance in
`MutilatedChessboard.lean` to a {board} × {board} board with its two opposite
(same-colour) corners removed.  The colour-counting argument is unchanged: each
domino covers one black and one white cell, but removing two same-colour corners
leaves a colour imbalance of 2, so no domino tiling exists.

The encoding is the same exact-cover order encoding: one Boolean placement
variable per pair of orthogonally adjacent remaining cells ({nplace} placements)
and a per-cell `sum_eq … = 1`, discharged by a single application of the generic
`csp_unsat` theorem over the committed certificate `certs/mutilated{board}.pbp`
(a {len(cert)}-char kernel proof; the single `pol` step is the colour-counting
linear combination).  The mutilated chessboard is exponentially hard for
resolution (Alekhnovich) but easy for cutting planes.  Generated by
`experiments/lib/gen_mutilated_lean.py`.
-/

/-- The {nplace} domino-placement variables (one per orthogonally adjacent pair of
    remaining cells), each in `{{0,1}}`, with a per-cell exactly-one constraint. -/
def mutilatedChessboard{board} : IntCSP :=
  ⟨{nplace}, ((List.finRange {nplace}).map (fun i => bound i 0 1))
      ++ [
{csp_body}
      ]⟩

/-- **UNSAT via the generic pipeline** — the {board} × {board} mutilated chessboard has
    no domino tiling, kernel-checked through PBLean's verified reflection checker
    (`native_decide`; RoundingSat / veripb / serializer untrusted). -/
theorem mutilated_chessboard_{board}_unsat :
    ¬ mutilatedChessboard{board}.isSatisfiableInt :=
  csp_unsat_file mutilatedChessboard{board} {nplace} "certs/mutilated{board}.pbp"

end CSP.L2S.PB.{ns}
'''


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--module-only"]
    module_only = "--module-only" in sys.argv[1:]
    k = int(args[0])
    if module_only:
        cert = (CERT_DIR / f"mutilated{2 * k}.pbp").read_text()
    else:
        cert = gen_cert(k)
    sys.stdout.write(gen(k, cert))
